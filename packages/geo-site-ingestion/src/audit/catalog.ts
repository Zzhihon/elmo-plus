export const SITE_AUDIT_RULES: readonly SiteAuditRule[] = RULES;

const BY_ID = new Map(RULES.map((rule) => [rule.id, rule]));

export function siteAuditRule(id: string): SiteAuditRule | undefined {
	return BY_ID.get(id);
}

export function isSiteAuditRuleId(id: string): boolean {
	return BY_ID.has(id);
}

const BASE_PRIORITY: Record<GeoFindingSeverity, GeoPriority> = { HIGH: "P1", MEDIUM: "P2", LOW: "P3", INFO: "P3" };
const RAISED: Record<GeoPriority, GeoPriority> = { P0: "P0", P1: "P0", P2: "P1", P3: "P2" };

/**
 * Severity sets the base; a problem that affects the whole site, the home page,
 * a key section or a product page is raised one step because it is seen most.
 */
export function findingPriorityOf(severity: GeoFindingSeverity, prominent: boolean): GeoPriority {
	const base = BASE_PRIORITY[severity];
	return prominent ? RAISED[base] : base;
}

